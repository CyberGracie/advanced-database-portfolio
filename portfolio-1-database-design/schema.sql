DROP TABLE IF EXISTS audit_log, reversals, transfers, ledger_entries,
  transactions, accounts, kyc_documents, staff, customers, account_types CASCADE;

-- Reference data: the kinds of account NairaFlow offers
CREATE TABLE account_types (
  account_type_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_name            VARCHAR(30)   NOT NULL UNIQUE
                       CHECK (type_name IN ('SAVINGS', 'CURRENT', 'WALLET')),
  daily_transfer_limit NUMERIC(15,2) NOT NULL CHECK (daily_transfer_limit > 0)
);

CREATE TABLE customers (
  customer_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR(50)  NOT NULL,
  last_name     VARCHAR(50)  NOT NULL,
  email         VARCHAR(100) NOT NULL UNIQUE,
  phone         VARCHAR(20)  NOT NULL UNIQUE,
  bvn           CHAR(11)     NOT NULL UNIQUE CHECK (bvn ~ '^[0-9]{11}$'),
  date_of_birth DATE         NOT NULL,
  kyc_status    VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                CHECK (kyc_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
  created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE staff (
  staff_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name  VARCHAR(100) NOT NULL,
  email      VARCHAR(100) NOT NULL UNIQUE,
  role       VARCHAR(30)  NOT NULL
             CHECK (role IN ('TELLER', 'OPERATIONS', 'COMPLIANCE', 'AUDITOR')),
  created_at TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE kyc_documents (
  document_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     INT         NOT NULL REFERENCES customers (customer_id),
  document_type   VARCHAR(30) NOT NULL
                  CHECK (document_type IN ('NIN', 'PASSPORT', 'DRIVERS_LICENCE')),
  document_number VARCHAR(50) NOT NULL,
  verified_by     INT REFERENCES staff (staff_id),          -- optional until verified
  verified_at     TIMESTAMP,
  UNIQUE (document_type, document_number),
  -- verifier and verification time are recorded together or not at all
  CHECK ((verified_by IS NULL) = (verified_at IS NULL))
);

CREATE TABLE accounts (
  account_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_number  CHAR(10)      NOT NULL UNIQUE CHECK (account_number ~ '^[0-9]{10}$'),  -- NUBAN
  customer_id     INT           NOT NULL REFERENCES customers (customer_id),
  account_type_id INT           NOT NULL REFERENCES account_types (account_type_id),
  balance         NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),  -- cached; audited against ledger
  currency        CHAR(3)       NOT NULL DEFAULT 'NGN',
  status          VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE'
                  CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
  opened_at       TIMESTAMP     NOT NULL DEFAULT now()
);

-- Every money movement is one transaction
CREATE TABLE transactions (
  transaction_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference        VARCHAR(30)   NOT NULL UNIQUE,
  transaction_type VARCHAR(20)   NOT NULL
                   CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER', 'REVERSAL')),
  amount           NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING'
                   CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED')),
  created_at       TIMESTAMP     NOT NULL DEFAULT now(),
  completed_at     TIMESTAMP,
  CHECK (completed_at IS NULL OR completed_at >= created_at)
);

-- Double-entry ledger: each successful movement writes a DEBIT and/or CREDIT row
CREATE TABLE ledger_entries (
  entry_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT        NOT NULL REFERENCES transactions (transaction_id),
  account_id     INT           NOT NULL REFERENCES accounts (account_id),
  entry_type     VARCHAR(6)    NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
  amount         NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  balance_after  NUMERIC(15,2) NOT NULL,
  created_at     TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE TABLE transfers (
  transfer_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id             BIGINT       NOT NULL UNIQUE REFERENCES transactions (transaction_id),
  source_account_id          INT          NOT NULL REFERENCES accounts (account_id),
  destination_account_id     INT REFERENCES accounts (account_id),  -- internal transfers only
  beneficiary_bank_code      CHAR(6),                               -- interbank transfers only
  beneficiary_account_number CHAR(10),                              -- interbank transfers only
  beneficiary_name           VARCHAR(100),
  idempotency_key            VARCHAR(64)  NOT NULL UNIQUE,          -- blocks duplicate requests
  failure_reason             VARCHAR(255),
  -- a transfer goes EITHER to a NairaFlow account OR to an external bank, never both
  CONSTRAINT chk_transfer_destination CHECK (
    (destination_account_id IS NOT NULL
       AND beneficiary_bank_code IS NULL AND beneficiary_account_number IS NULL)
    OR
    (destination_account_id IS NULL
       AND beneficiary_bank_code IS NOT NULL AND beneficiary_account_number IS NOT NULL)
  ),
  CONSTRAINT chk_not_self_transfer CHECK (source_account_id <> destination_account_id)
);

CREATE TABLE reversals (
  reversal_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_transaction_id BIGINT       NOT NULL UNIQUE REFERENCES transactions (transaction_id),
  reversal_transaction_id BIGINT       NOT NULL UNIQUE REFERENCES transactions (transaction_id),
  reason                  VARCHAR(255) NOT NULL,
  approved_by             INT          NOT NULL REFERENCES staff (staff_id),
  reversed_at             TIMESTAMP    NOT NULL DEFAULT now(),
  CHECK (original_transaction_id <> reversal_transaction_id)
);

-- Filled automatically by triggers (audit-triggers.sql)
CREATE TABLE audit_log (
  audit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name   VARCHAR(50) NOT NULL,
  record_id    BIGINT      NOT NULL,
  action       VARCHAR(10) NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
  old_values   JSONB,
  new_values   JSONB,
  performed_by VARCHAR(50) NOT NULL DEFAULT current_user,
  performed_at TIMESTAMP   NOT NULL DEFAULT now()
);

